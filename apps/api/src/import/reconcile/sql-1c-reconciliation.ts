/**
 * SQL (legacy MySQL dump) ↔ 1C feed reconciliation (Sprint 12A.3).
 *
 * Purely read-only, in-memory analysis: no database writes, no mutation of
 * `external_entity_mappings`, and it never auto-resolves a Sprint 12A.2
 * quarantine item. It reuses the already-parsed MySQL catalog
 * (`../parsers/mysql-catalog.ts`) and the already-parsed 1C products feed
 * (`../parsers/products-feed.ts`) - it does not parse either source itself.
 *
 * IMPORTANT: as of Sprint 12A.3 there is no real 1C export in this repo.
 * The only 1C-shaped file available (`docs/legacy-reference/
 * legacy-feed-samples.json`) is explicitly labeled in its own `meta.purpose`
 * as an anonymized sample for designing the V2 import, not a real export -
 * see `docs/legacy-reference/legacy-feed-samples.json`. This module is
 * therefore built generically against whatever `ProductsFeedRecord[]` the
 * existing Sprint 10A Zod parser validates, and this sprint runs it only as
 * a capability demo against that sample file - never as a claim that a real
 * reconciliation has been performed. See
 * `docs/vizaje-sql-1c-reconciliation.md` §"What real 1C data is needed"
 * for exactly what inputs a genuine run requires.
 *
 * Matching key priority (justified in docs/vizaje-sql-1c-reconciliation.md
 * §2, summarized here):
 *   1. GUID (MySQL `products.GUID`) ↔ `ID_nom` (1C) - the *primary* identity
 *      link. `docs/legacy-reference/workapp-1c-observed-contract.md` §3
 *      confirms Legacy's own GUID "в Legacy при создании берётся из
 *      ID_nom" (taken from ID_nom at creation time) - so a GUID/ID_nom hit
 *      is not a coincidence, it is the system's own original identity
 *      relationship, re-derived here rather than assumed.
 *   2. Barcode - a real-world physical/supplier identifier present on both
 *      sides, strong but secondary to GUID/ID_nom (a barcode can
 *      legitimately be shared across resellers/repacks in ways a
 *      system-assigned id cannot).
 *   3. VariativeNomenclature (1C) ↔ a detected MySQL group-code pattern in
 *      `products.SKU` (Sprint 12A.2 §13.3 found this exact pattern, e.g.
 *      `"A10.XXX"`, already shared with the confirmed-real 1C
 *      `VariativeNomenclature` value for the ANNY fixture from Sprint
 *      10A.1) - a *grouping*-level signal, not a single-record identity
 *      match on its own; only promoted to a record-level match when the
 *      group resolves to exactly one MySQL product and exactly one 1C
 *      record.
 *   4. SKU - explicitly NOT used as a cross-system match key. Per
 *      `workapp-1c-observed-contract.md` §3, `SKU` is "локальный SKU,
 *      формируемый при импорте из входной номенклатуры" (a *local* SKU,
 *      generated by Legacy at import time) - it does not exist in the 1C
 *      products feed shape at all (see `ProductsFeedRecord` in
 *      `../parsers/products-feed.ts`: no `SKU` field). Listing it here only
 *      to record, explicitly, why it is not a usable key with the inputs
 *      available today.
 */
import type { LegacyCatalogDump, LegacyProduct } from '../parsers/mysql-catalog'
import type { ProductsFeedRecord } from '../parsers/products-feed'
import type { QuarantineReasonCode } from '../dry-run-catalog'

export type ReconciliationMatchKey = 'guid_id_nom' | 'barcode' | 'variative_nomenclature_group'

export type MatchBasisEntry = {
	key: ReconciliationMatchKey
	mysqlValue: string
	oneCValue: string
}

export type ReconciliationOutcome = 'confirmed' | 'ambiguous' | 'unmatched' | 'quarantine'

export type MysqlReconciliationResult = {
	legacyProductId: number
	mysqlGuid: string | null
	outcome: ReconciliationOutcome
	/** Every key that produced a candidate, even when the overall outcome is ambiguous/unmatched - never collapsed to a single value, so a human reviewer can see exactly what was tried. */
	basis: MatchBasisEntry[]
	matchedOneCIdNoms: string[]
	reasoning: string
	/**
	 * Carried over verbatim from the Sprint 12A.2 catalog dry-run when this
	 * product was already quarantined there. Reconciliation against 1C never
	 * clears a quarantine on its own - a matching 1C record is useful
	 * evidence for a human resolving the quarantine, not an automatic
	 * resolution.
	 */
	priorQuarantineReasonCodes?: QuarantineReasonCode[]
}

export type UnmatchedOneCRecord = {
	idNom: string
	variativeNomenclature: string | null
	barcode: string | null
	reasoning: string
}

export type ReconciliationSummary = {
	totalMysqlProducts: number
	totalOneCRecords: number
	confirmed: number
	ambiguous: number
	unmatched: number
	quarantine: number
	unmatchedOneCRecordCount: number
	byMatchKey: Record<ReconciliationMatchKey, number>
	examples: Record<ReconciliationOutcome, { legacyProductId: number; note: string }[]>
}

export type ReconciliationResult = {
	summary: ReconciliationSummary
	mysqlResults: MysqlReconciliationResult[]
	unmatchedOneCRecords: UnmatchedOneCRecord[]
}

const EXAMPLE_LIMIT = 3

/**
 * Sprint 12A.2 §13.3's observed group-code shape: a short alpha prefix,
 * digits, then a dot-separated suffix (the `"A10.XXX"`, `"A8.XXX.XX"`,
 * `"1502artdeco"`-style values already found in the real duplicate-SKU
 * groups). Deliberately loose - this is a *candidate* detector, never
 * treated as proof on its own; it only contributes a match when it also
 * resolves to an unambiguous 1:1 pairing.
 */
const GROUP_CODE_PATTERN = /^[a-z]{0,3}\d+[a-z]*\.[a-z0-9.]+$/i

function detectGroupCode(sku: string | null): string | null {
	if (sku === null) return null
	return GROUP_CODE_PATTERN.test(sku) ? sku : null
}

function buildGuidIndex(oneC: ProductsFeedRecord[]): Map<string, ProductsFeedRecord[]> {
	const index = new Map<string, ProductsFeedRecord[]>()
	for (const record of oneC) {
		const list = index.get(record.ID_nom) ?? []
		list.push(record)
		index.set(record.ID_nom, list)
	}
	return index
}

function buildBarcodeIndex(oneC: ProductsFeedRecord[]): Map<string, ProductsFeedRecord[]> {
	const index = new Map<string, ProductsFeedRecord[]>()
	for (const record of oneC) {
		if (record.Barcode === null) continue
		const list = index.get(record.Barcode) ?? []
		list.push(record)
		index.set(record.Barcode, list)
	}
	return index
}

function buildVariativeIndex(oneC: ProductsFeedRecord[]): Map<string, ProductsFeedRecord[]> {
	const index = new Map<string, ProductsFeedRecord[]>()
	for (const record of oneC) {
		if (record.VariativeNomenclature === null) continue
		const list = index.get(record.VariativeNomenclature) ?? []
		list.push(record)
		index.set(record.VariativeNomenclature, list)
	}
	return index
}

function matchProduct(
	product: LegacyProduct,
	groupCodeOwners: Map<string, number[]>,
	guidIndex: Map<string, ProductsFeedRecord[]>,
	barcodeIndex: Map<string, ProductsFeedRecord[]>,
	variativeIndex: Map<string, ProductsFeedRecord[]>
): { outcome: 'confirmed' | 'ambiguous' | 'unmatched'; basis: MatchBasisEntry[]; matchedIdNoms: string[]; reasoning: string } {
	const basis: MatchBasisEntry[] = []
	const candidateIdNoms = new Set<string>()

	// 1. GUID == ID_nom (primary).
	let guidMatches: ProductsFeedRecord[] = []
	if (product.guid !== null) {
		guidMatches = guidIndex.get(product.guid) ?? []
		for (const m of guidMatches) {
			basis.push({ key: 'guid_id_nom', mysqlValue: product.guid, oneCValue: m.ID_nom })
			candidateIdNoms.add(m.ID_nom)
		}
	}

	// 2. Barcode (secondary, independent signal - checked regardless of
	// whether GUID already matched, so a conflict between the two can be
	// surfaced rather than hidden by short-circuiting).
	let barcodeMatches: ProductsFeedRecord[] = []
	if (product.barcode !== null) {
		barcodeMatches = barcodeIndex.get(product.barcode) ?? []
		for (const m of barcodeMatches) {
			basis.push({ key: 'barcode', mysqlValue: product.barcode, oneCValue: m.ID_nom })
			candidateIdNoms.add(m.ID_nom)
		}
	}

	// 3. Group-code (products.SKU) <-> VariativeNomenclature - only
	// contributes when the MySQL-side group resolves to exactly this one
	// product (otherwise it's a many-to-many grouping signal, not a
	// single-record match) and the 1C-side group resolves to exactly one
	// record.
	const groupCode = detectGroupCode(product.sku)
	let groupMatches: ProductsFeedRecord[] = []
	if (groupCode !== null) {
		const mysqlSiblings = groupCodeOwners.get(groupCode) ?? []
		const oneCGroup = variativeIndex.get(groupCode) ?? []
		if (mysqlSiblings.length === 1 && oneCGroup.length === 1) {
			groupMatches = oneCGroup
			basis.push({ key: 'variative_nomenclature_group', mysqlValue: groupCode, oneCValue: oneCGroup[0].ID_nom })
			candidateIdNoms.add(oneCGroup[0].ID_nom)
		}
	}

	if (candidateIdNoms.size === 0) {
		return {
			outcome: 'unmatched',
			basis,
			matchedIdNoms: [],
			reasoning:
				product.guid === null && product.barcode === null && groupCode === null
					? 'no GUID, barcode, or group-code SKU available to match against the 1C feed'
					: 'no 1C record found on any available key (GUID/ID_nom, barcode, or group-code)'
		}
	}

	if (candidateIdNoms.size === 1 && guidMatches.length <= 1 && barcodeMatches.length <= 1 && groupMatches.length <= 1) {
		const idNom = [...candidateIdNoms][0]
		const keysAgreeing = basis.filter(b => b.oneCValue === idNom).map(b => b.key)
		return {
			outcome: 'confirmed',
			basis,
			matchedIdNoms: [idNom],
			reasoning: `unambiguous match on ${keysAgreeing.join(', ')}`
		}
	}

	return {
		outcome: 'ambiguous',
		basis,
		matchedIdNoms: [...candidateIdNoms],
		reasoning:
			candidateIdNoms.size > 1
				? `multiple distinct 1C candidates found (${[...candidateIdNoms].join(', ')}) across the available keys - conflicting or duplicate signals`
				: 'a single key matched more than one 1C record (duplicate ID_nom/barcode in the 1C input)'
	}
}

/**
 * @param dump Already-parsed MySQL catalog (Sprint 12 Phase A's `loadLegacyCatalogDump`).
 * @param oneCRecords Already-parsed/validated 1C products-feed records (Sprint 10A's `parseProductsFeed(...).validRecords`).
 * @param priorQuarantine Optional map of legacyProductId -> quarantine reason codes from the Sprint 12A.2 catalog dry-run. When supplied, a quarantined product's outcome here is always `'quarantine'`, regardless of how well it matches 1C - matching evidence is still computed and attached for a human reviewer, it just never overrides the quarantine.
 */
export function reconcileSqlWith1c(
	dump: LegacyCatalogDump,
	oneCRecords: ProductsFeedRecord[],
	priorQuarantine?: Map<number, QuarantineReasonCode[]>
): ReconciliationResult {
	const guidIndex = buildGuidIndex(oneCRecords)
	const barcodeIndex = buildBarcodeIndex(oneCRecords)
	const variativeIndex = buildVariativeIndex(oneCRecords)

	const groupCodeOwners = new Map<string, number[]>()
	for (const p of dump.products) {
		const code = detectGroupCode(p.sku)
		if (code === null) continue
		const list = groupCodeOwners.get(code) ?? []
		list.push(p.id)
		groupCodeOwners.set(code, list)
	}

	const mysqlResults: MysqlReconciliationResult[] = []
	const counts: Record<ReconciliationOutcome, number> = { confirmed: 0, ambiguous: 0, unmatched: 0, quarantine: 0 }
	const byMatchKey: Record<ReconciliationMatchKey, number> = { guid_id_nom: 0, barcode: 0, variative_nomenclature_group: 0 }
	const exampleIds: Record<ReconciliationOutcome, number[]> = { confirmed: [], ambiguous: [], unmatched: [], quarantine: [] }
	const matchedIdNomsOverall = new Set<string>()

	for (const product of dump.products) {
		const existingQuarantine = priorQuarantine?.get(product.id)
		const { outcome: rawOutcome, basis, matchedIdNoms, reasoning } = matchProduct(
			product,
			groupCodeOwners,
			guidIndex,
			barcodeIndex,
			variativeIndex
		)
		for (const b of basis) byMatchKey[b.key]++
		for (const idNom of matchedIdNoms) matchedIdNomsOverall.add(idNom)

		const outcome: ReconciliationOutcome =
			existingQuarantine !== undefined && existingQuarantine.length > 0 ? 'quarantine' : rawOutcome
		counts[outcome]++
		if (exampleIds[outcome].length < EXAMPLE_LIMIT) exampleIds[outcome].push(product.id)

		mysqlResults.push({
			legacyProductId: product.id,
			mysqlGuid: product.guid,
			outcome,
			basis,
			matchedOneCIdNoms: matchedIdNoms,
			reasoning:
				outcome === 'quarantine'
					? `already quarantined by the Sprint 12A.2 catalog dry-run (${existingQuarantine?.join(', ')}) - reconciliation evidence attached but does not clear the quarantine. 1C match attempt: ${reasoning}`
					: reasoning,
			priorQuarantineReasonCodes: existingQuarantine
		})
	}

	const unmatchedOneCRecords: UnmatchedOneCRecord[] = oneCRecords
		.filter(r => !matchedIdNomsOverall.has(r.ID_nom))
		.map(r => ({
			idNom: r.ID_nom,
			variativeNomenclature: r.VariativeNomenclature,
			barcode: r.Barcode,
			reasoning: 'no MySQL product matched this ID_nom on GUID, barcode, or group-code'
		}))

	const examples: ReconciliationSummary['examples'] = {
		confirmed: exampleIds.confirmed.map(id => ({ legacyProductId: id, note: 'unambiguous match found' })),
		ambiguous: exampleIds.ambiguous.map(id => ({ legacyProductId: id, note: 'multiple or conflicting 1C candidates' })),
		unmatched: exampleIds.unmatched.map(id => ({ legacyProductId: id, note: 'no 1C candidate on any key' })),
		quarantine: exampleIds.quarantine.map(id => ({ legacyProductId: id, note: 'already quarantined independent of 1C reconciliation' }))
	}

	return {
		summary: {
			totalMysqlProducts: dump.products.length,
			totalOneCRecords: oneCRecords.length,
			confirmed: counts.confirmed,
			ambiguous: counts.ambiguous,
			unmatched: counts.unmatched,
			quarantine: counts.quarantine,
			unmatchedOneCRecordCount: unmatchedOneCRecords.length,
			byMatchKey,
			examples
		},
		mysqlResults,
		unmatchedOneCRecords
	}
}

/** Convenience: build the `priorQuarantine` map straight from a Sprint 12A.2 `CatalogDryRunResult.products` list. */
export function quarantineMapFromCatalogDryRun(
	products: { legacyProductId: number; quarantineReasonCodes: QuarantineReasonCode[] }[]
): Map<number, QuarantineReasonCode[]> {
	const map = new Map<number, QuarantineReasonCode[]>()
	for (const p of products) {
		if (p.quarantineReasonCodes.length > 0) map.set(p.legacyProductId, p.quarantineReasonCodes)
	}
	return map
}
